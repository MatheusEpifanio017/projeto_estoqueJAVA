-- Projeto Integrador UC6 - Base de dados para análise de uma clínica fictícia
-- SGBD: PostgreSQL 14 ou superior
-- Todos os dados são fictícios e anonimizados.
--
-- Uso sugerido:
--   psql -U seu_usuario -d seu_banco -f clinica_pi_uc6_postgresql.sql
--
-- Atenção: a primeira instrução remove e recria somente o schema clinica_pi_uc6.

DROP SCHEMA IF EXISTS clinica_pi_uc6 CASCADE;
CREATE SCHEMA clinica_pi_uc6;
SET search_path TO clinica_pi_uc6, public;

CREATE TABLE especialidade (
    id_especialidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    descricao VARCHAR(255) NOT NULL
);

CREATE TABLE convenio (
    id_convenio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_convenio_tipo CHECK (tipo IN ('PARTICULAR', 'SAUDE', 'EMPRESARIAL'))
);

CREATE TABLE consultorio (
    id_consultorio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    andar SMALLINT NOT NULL,
    capacidade SMALLINT NOT NULL DEFAULT 1,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_consultorio_andar CHECK (andar BETWEEN 1 AND 10),
    CONSTRAINT ck_consultorio_capacidade CHECK (capacidade > 0)
);

CREATE TABLE profissional (
    id_profissional INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    registro_profissional VARCHAR(30) NOT NULL UNIQUE,
    id_especialidade INTEGER NOT NULL REFERENCES especialidade(id_especialidade),
    data_admissao DATE NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE paciente (
    id_paciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    data_nascimento DATE NOT NULL,
    sexo CHAR(1) NOT NULL,
    cidade VARCHAR(80) NOT NULL,
    id_convenio INTEGER NOT NULL REFERENCES convenio(id_convenio),
    data_cadastro DATE NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_paciente_sexo CHECK (sexo IN ('F', 'M', 'X')),
    CONSTRAINT ck_paciente_nascimento CHECK (data_nascimento < CURRENT_DATE)
);

CREATE TABLE consulta (
    id_consulta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL REFERENCES paciente(id_paciente),
    id_profissional INTEGER NOT NULL REFERENCES profissional(id_profissional),
    id_consultorio INTEGER NOT NULL REFERENCES consultorio(id_consultorio),
    data_agendamento TIMESTAMP NOT NULL,
    data_hora_consulta TIMESTAMP NOT NULL,
    status VARCHAR(15) NOT NULL,
    tipo_atendimento VARCHAR(20) NOT NULL,
    valor_cobrado NUMERIC(10,2),
    inicio_atendimento TIMESTAMP,
    fim_atendimento TIMESTAMP,
    observacao VARCHAR(255),
    CONSTRAINT ck_consulta_status CHECK (status IN ('AGENDADA', 'REALIZADA', 'FALTOU', 'CANCELADA')),
    CONSTRAINT ck_consulta_tipo CHECK (tipo_atendimento IN ('PRESENCIAL', 'TELECONSULTA')),
    CONSTRAINT ck_consulta_agendamento CHECK (data_agendamento <= data_hora_consulta),
    CONSTRAINT ck_consulta_periodo CHECK (
        (inicio_atendimento IS NULL AND fim_atendimento IS NULL)
        OR (inicio_atendimento IS NOT NULL AND fim_atendimento IS NOT NULL AND fim_atendimento >= inicio_atendimento)
    )
);

CREATE INDEX idx_profissional_especialidade ON profissional(id_especialidade);
CREATE INDEX idx_paciente_convenio ON paciente(id_convenio);
CREATE INDEX idx_consulta_paciente ON consulta(id_paciente);
CREATE INDEX idx_consulta_profissional_data ON consulta(id_profissional, data_hora_consulta);
CREATE INDEX idx_consulta_status_data ON consulta(status, data_hora_consulta);

COMMENT ON SCHEMA clinica_pi_uc6 IS 'Fictitious clinic database for UC6 data-analysis project.';
