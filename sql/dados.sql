-- Os padrões dos dados foram intencionalmente construídos para permitir análises.
-- Há maior volume em Clínica Geral e Psicologia, mais faltas em determinados perfis
-- e pacientes recorrentes. Estudantes devem descobrir e justificar esses padrões por SQL.
WITH base AS (
    SELECT
        serie,
        CASE
            WHEN serie % 20 < 5 THEN 1
            WHEN serie % 20 < 8 THEN 2
            WHEN serie % 20 < 11 THEN 3
            WHEN serie % 20 < 13 THEN 4
            WHEN serie % 20 < 15 THEN 5
            WHEN serie % 20 < 17 THEN 6
            WHEN serie % 20 < 18 THEN 7
            WHEN serie % 20 < 19 THEN 8
            ELSE 9
        END AS id_profissional,
        CASE
            WHEN serie % 12 < 3 THEN (serie % 12) + 1
            WHEN serie % 12 < 6 THEN (serie % 30) + 1
            ELSE (serie % 80) + 1
        END AS id_paciente,
        TIMESTAMP '2026-01-05 08:00:00'
            + ((serie * 7) % 238) * INTERVAL '1 day'
            + ((serie % 9) * INTERVAL '1 hour') AS data_hora_consulta
    FROM generate_series(1, 720) AS serie
), agenda AS (
    SELECT
        base.*,
        CASE
            WHEN serie % 17 = 0 OR (serie % 11 = 0 AND id_profissional IN (8, 9)) THEN 'FALTOU'
            WHEN serie % 29 = 0 THEN 'CANCELADA'
            WHEN serie % 31 = 0 THEN 'AGENDADA'
            ELSE 'REALIZADA'
        END AS status
    FROM base
)
