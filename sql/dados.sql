    CASE WHEN id_profissional IN (8, 9) AND serie % 4 = 0 THEN 5 ELSE ((id_profissional - 1) % 4) + 1 END,
    data_hora_consulta - ((serie % 21) + 1) * INTERVAL '1 day',
    data_hora_consulta,
    status,
    CASE WHEN id_profissional IN (8, 9) AND serie % 4 = 0 THEN 'TELECONSULTA' ELSE 'PRESENCIAL' END,
    CASE
        WHEN status = 'REALIZADA' THEN
            CASE id_profissional
                WHEN 1 THEN 180.00 WHEN 2 THEN 170.00
                WHEN 3 THEN 240.00 WHEN 4 THEN 220.00
                WHEN 5 THEN 190.00 WHEN 6 THEN 210.00
                WHEN 7 THEN 230.00 WHEN 8 THEN 160.00 ELSE 150.00
            END
        ELSE NULL
    END,
    CASE WHEN status = 'REALIZADA' THEN data_hora_consulta + (serie % 8) * INTERVAL '1 minute' ELSE NULL END,
    CASE WHEN status = 'REALIZADA' THEN data_hora_consulta + (35 + (serie % 26)) * INTERVAL '1 minute' ELSE NULL END,
    CASE status
        WHEN 'FALTOU' THEN 'Paciente não compareceu ao horário agendado.'
        WHEN 'CANCELADA' THEN 'Agendamento cancelado antes do atendimento.'
        WHEN 'AGENDADA' THEN 'Consulta futura aguardando atendimento.'
        ELSE 'Atendimento concluído.'
    END
FROM agenda;

